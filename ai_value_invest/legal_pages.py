def _sub_operator(obj, op):
    if isinstance(obj, str):
        wtok = "{{OP:wechat}}"
        wv = str(op.get("wechat") or "")
        if wtok in obj:
            obj = obj.replace("　微信：" + wtok, ("　微信：" + wv) if wv else "")
        for k, v in op.items():
            obj = obj.replace("{{OP:%s}}" % k, str(v))
        return obj
    if isinstance(obj, dict):
        return {k: _sub_operator(v, op) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_sub_operator(v, op) for v in obj]
    return obj

