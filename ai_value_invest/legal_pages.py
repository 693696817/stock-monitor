def get_page(slug):
    page = PAGES.get(slug)
    if not page:
        return None
    return _sub_operator(page, effective_operator())

def pending_placeholders():
    return {k: v for k, v in effective_operator().items()
            if "【待填写" in str(v)}

INDEXABLE_SLUGS = {"about", "contact", "help"}

def is_indexable(slug):
    if slug not in INDEXABLE_SLUGS:
        return False
    return not pending_placeholders()

